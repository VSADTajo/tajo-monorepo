export class ListManualSimulationsMapper {
    static toQuery(dto: ListManualSimulationsQueryDto): ListManualSimulationsQuery {
        return new ListManualSimulationsQuery({
            status: dto.status,
            stationCode: dto.stationCode,
            sortBy: dto.sortBy,
            sortOrder: dto.sortOrder,
            page: dto.page ?? 1,
            limit: dto.limit ?? 20,
        });
    }

    static toResponseDto(result: PaginatedManualSimulationResult): ListManualSimulationsResponseDto {
        return {
            data: result.data.map(
                (item): ManualSimulationListItemDto => ({
                    id: item.simulation.id,
                    simulationDate: item.simulation.simulationDate,
                    status: item.simulation.status,
                    type: item.simulation.type,
                    description: item.simulation.description ?? null,
                    maneuverCount: item.maneuvers.length,
                    maneuvers: item.maneuvers.map(
                        (m: Maneuver): ManeuverResponseDto => ({
                            id: m.id,
                            reservoirCode: m.reservoirCode,
                            outputFlowValue: Number(m.outputFlowValue),
                            startDate: m.startDate ?? null,
                            endDate: m.endDate ?? null,
                        }),
                    ),
                    createdAt: item.simulation.createdAt,
                }),
            ),
            total: result.total,
            page: result.page,
            limit: result.limit,
        };
    }
}

// ─────────────────────────────────────────────────────────────
// GetSimulationResults
// ─────────────────────────────────────────────────────────────

export class GetSimulationResultsMapper {
    static toQuery(id: string, filters?: { stationCode?: string; type?: string }): GetSimulationResultsQuery {
        return new GetSimulationResultsQuery({
            id,
            stationCode: filters?.stationCode,
            typeName: filters?.type,
        });
    }

    static toResponseDto(result: SimulationResultsResult): GetSimulationResultsResponseDto {
        return {
            simulation: {
                id: result.simulation.id,
                simulationDate: result.simulation.simulationDate,
                status: result.simulation.status,
                type: result.simulation.type,
                dataOrigin: result.simulation.dataOrigin ?? null,
                createdAt: result.simulation.createdAt,
                updatedAt: result.simulation.updatedAt,
            },
            predictions: result.predictions.map((p) => {
                const results = (p.results ?? []).map((r) => ({
                    date: r.date,
                    value: typeof r.value === 'string' ? Number(r.value) : r.value,
                    flag: r.flag,
                }));
                // results come pre-ordered by date ASC from the repository query
                const last = results.length > 0 ? results[results.length - 1] : null;
                const max =
                    results.length > 0
                        ? results.reduce((acc, cur) => (cur.value > acc.value ? cur : acc), results[0])
                        : null;
                const station = result.stationsByCode.get(p.stationId?.toLowerCase() ?? '') ?? null;
                return {
                    id: p.id,
                    stationId: p.stationId,
                    stationName: p.stationName ?? null,
                    station,
                    predictionTypeId: p.predictionTypeId,
                    predictionTypeName: p.predictionType?.name ?? null,
                    predictionTypeUnit: p.predictionType?.unit ?? null,
                    percentile: p.percentile !== null && p.percentile !== undefined ? Number(p.percentile) : null,
                    predictionProvider: p.predictionProvider ?? null,
                    predictedBy: p.predictedBy ?? null,
                    predictionDate: p.predictionDate ?? null,
                    predictionStartDate: p.predictionStartDate ?? null,
                    predictionEndDate: p.predictionEndDate ?? null,
                    results,
                    max,
                    last,
                };
            }),
        };
    }
}
